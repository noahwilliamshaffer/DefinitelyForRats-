#!/usr/bin/env node
/* ============================================================================
   Create a Stripe Payment Link for every product in js/products.js and write
   the id -> URL map to js/payment-links.js.

   Requires: Node 18+ (uses built-in fetch). No npm install needed.

   Your Stripe SECRET key is read from the STRIPE_SECRET_KEY environment
   variable and is used only to talk to api.stripe.com from THIS machine. It is
   never written to any file and never leaves your terminal.

   Usage (PowerShell):
     $env:STRIPE_SECRET_KEY="sk_test_xxx"; node scripts/create-stripe-payment-links.mjs

   Usage (bash/zsh):
     STRIPE_SECRET_KEY=sk_test_xxx node scripts/create-stripe-payment-links.mjs

   Re-running is safe: products that already have a link are reused, only new
   ones are created. Delete an entry from js/payment-links.js to regenerate it.
   ========================================================================== */
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const KEY = process.env.STRIPE_SECRET_KEY;
if (!KEY || !/^sk_(test|live)_/.test(KEY)) {
  console.error("✗ Set STRIPE_SECRET_KEY to your Stripe secret key (sk_test_... or sk_live_...).");
  console.error("  PowerShell:  $env:STRIPE_SECRET_KEY=\"sk_test_...\"; node scripts/create-stripe-payment-links.mjs");
  process.exit(1);
}
const MODE = KEY.startsWith("sk_live_") ? "LIVE" : "TEST";

const productsUrl = new URL("../js/products.js", import.meta.url);
const linksUrl = new URL("../js/payment-links.js", import.meta.url);
const CURRENCY = "usd";

// Load window.PRODUCTS by evaluating js/products.js in a tiny sandbox.
const win = {};
new Function("window", fs.readFileSync(productsUrl, "utf8"))(win);
const products = win.PRODUCTS || [];

// Reuse any links already generated.
let existing = {};
try {
  const m = fs.readFileSync(linksUrl, "utf8").match(/window\.PAYMENT_LINKS\s*=\s*(\{[\s\S]*?\});/);
  if (m) existing = JSON.parse(m[1]);
} catch { /* first run */ }

async function stripe(endpoint, params) {
  const res = await fetch("https://api.stripe.com/v1/" + endpoint, {
    method: "POST",
    headers: {
      Authorization: "Bearer " + KEY,
      "Content-Type": "application/x-www-form-urlencoded"
    },
    body: new URLSearchParams(params)
  });
  const json = await res.json();
  if (!res.ok) throw new Error((json.error && json.error.message) || ("HTTP " + res.status));
  return json;
}

const priceCents = (p) => Math.round((p.sale != null ? p.sale : p.price) * 100);

console.log(`\nStripe ${MODE} mode — ${products.length} products\n`);

const out = {};
let created = 0, reused = 0, failed = 0;

for (const p of products) {
  if (existing[p.id]) { out[p.id] = existing[p.id]; reused++; continue; }
  try {
    // A Price with inline product_data creates the Product automatically.
    const price = await stripe("prices", {
      currency: CURRENCY,
      unit_amount: String(priceCents(p)),
      "product_data[name]": p.name
    });
    const link = await stripe("payment_links", {
      "line_items[0][price]": price.id,
      "line_items[0][quantity]": "1"
    });
    out[p.id] = link.url;
    created++;
    console.log(`  ✓ ${p.id.padEnd(20)} ${link.url}`);
  } catch (e) {
    failed++;
    console.error(`  ✗ ${p.id.padEnd(20)} ${e.message}`);
  }
}

const banner =
  "/* AUTO-GENERATED by scripts/create-stripe-payment-links.mjs — do not edit by hand.\n" +
  `   ${MODE} mode links, generated ${new Date().toISOString()}.\n` +
  "   Re-run the script to add new products. Safe to commit (public URLs). */\n";
fs.writeFileSync(
  fileURLToPath(linksUrl),
  banner + "window.PAYMENT_LINKS = " + JSON.stringify(out, null, 2) + ";\n"
);

console.log(`\nDone. Created ${created}, reused ${reused}, failed ${failed}.`);
console.log("Wrote js/payment-links.js — commit & push, then the Buy Now buttons are live.\n");
if (MODE === "TEST") console.log("NOTE: TEST links won't charge real cards. Re-run with an sk_live_ key for live checkout.\n");
